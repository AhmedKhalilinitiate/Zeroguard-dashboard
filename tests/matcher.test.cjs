const assert=require("node:assert/strict");
const m=require("../matcher.js");
const cve=(system)=>({id:"CVE-2026-12345",cvss:9.8,inKEV:true,affectedSystems:[system]});
const asset={id:"srv1",name:"widget",version:"1.5.0",purl:"pkg:npm/widget@1.5.0",host:"example",criticality:"high"};
const system={name:"npm: widget",version:">=1.0.0, <2.0.0",source:"GitHub Advisory (npm)",url:"https://github.com/advisories/GHSA-aaaa-bbbb-cccc"};
assert.equal(m.versionRange("1.5.0",system.version),"match");
assert.equal(m.versionRange("2.1.0",system.version),"exclude");
assert.equal(m.versionRange("beta",system.version),"unknown");
assert.equal(m.versionRange("1.5.0","See advisory for version applicability"),"unknown");
assert.equal(m.assess(asset,cve(system)).status,"version-match");
assert.equal(m.assess({...asset,version:"2.1.0",purl:"pkg:npm/widget@2.1.0"},cve(system)),null);
assert.equal(m.assess({id:"x",name:"widget",version:"1.5.0"},cve(system)).status,"review");
assert.equal(m.scan([asset],[cve(system)]).confirmed,1);
assert.equal(m.scan([{id:"a",name:"unrelated"}],[cve(system)]).findings.length,0);
const csv="id,name,vendor,version,purl,host\n1,widget,example,1.5.0,pkg:npm/widget@1.5.0,server-a\n";
assert.equal(m.parseInventory(csv,"input.csv")[0].host,"server-a");
const bom={bomFormat:"CycloneDX",specVersion:"1.6",components:[{name:"widget",version:"1.5.0",purl:"pkg:npm/widget@1.5.0"}]};
assert.equal(m.parseInventory(JSON.stringify(bom),"bom.json")[0].name,"widget");
const spdx={packages:[{name:"widget",versionInfo:"1.5.0",externalRefs:[{referenceType:"purl",referenceLocator:"pkg:npm/widget@1.5.0"}]}]};
assert.equal(m.parseInventory(JSON.stringify(spdx),"bom.json")[0].version,"1.5.0");
assert.equal(m.parseInventory("[]","bom.json").length,0);
assert.throws(()=>m.parseInventory('{"assets":[{"version":"1.0"}]}',"a.json"));
console.log("Asset matcher: 14 checks passed");
