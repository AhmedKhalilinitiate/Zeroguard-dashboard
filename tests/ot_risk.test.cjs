const assert=require("node:assert/strict");
const ot=require("../ot-risk.js");
const device={id:"S9005-01",name:"RSG2100",vendor:"Siemens",site:"9005",criticality:"unknown",exposure:"unknown",version:""};
const kev={assetId:device.id,assetName:device.name,cve:"CVE-2026-12345",status:"model-lead",kev:true};
assert.equal(ot.inventoryGaps(device).some(x=>x.field==="version"),true);
assert.equal(ot.inventoryGaps(device).some(x=>x.field==="exposure"),true);
assert.equal(ot.priority(kev,device).tier,"Expedited review");
assert.notEqual(ot.priority({...kev,status:"vendor-lead"},device).tier,"Expedited review");
assert.equal(ot.priority(kev,{...device,criticality:"high"}).tier,"Priority investigation");
assert.match(ot.confidence(kev),/firmware unknown/);
assert.equal(ot.recommendations(kev,device).controls.length,6);
const defaultReview=ot.sanitizeReview();
assert.equal(defaultReview.controls.segmentation.status,"Not assessed");
const evidenceClaim=ot.sanitizeReview({controls:{segmentation:{status:"Evidence verified",evidence:""}}});
assert.equal(evidenceClaim.controls.segmentation.status,"Existing - unverified");
const evidence=ot.sanitizeReview({controls:{segmentation:{status:"Evidence verified",evidence:"OT firewall policy approval #123"}}});
assert.equal(evidence.controls.segmentation.status,"Evidence verified");
const keyed=new Map([[ot.caseKey(kev),evidence]]);
const saved=ot.makePackage([device],keyed,"2026-10-25T08:00:00Z","2026-10-25T09:00:00Z");
const restored=ot.loadPackage(saved);
assert.equal(restored.assets[0].site,"9005");
assert.equal(restored.cases.get(ot.caseKey(kev)).controls.segmentation.status,"Evidence verified");
assert.throws(()=>ot.loadPackage({assets:[],caseReviews:{}}));
console.log("OT nonintrusive assessment, explicit evidence and portable-case tests passed");
